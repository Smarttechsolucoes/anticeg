// Processo filho: roda o script REAL do sync (uma cópia com o import do supabase-js trocado pelo stub) contra um PGlite montado a partir de um cenário JSON.
// Uso (feito por tests/sync-integracao.mjs):  node tests/helpers/sync-filho.mjs <cenario.json>
// Saída (stdout, última linha): JSON { logs, exitCode, masterlist, claims, exclusoes, joiners, push }.
import { PGlite } from "@electric-sql/pglite";
import { readFileSync, writeFileSync, unlinkSync, existsSync } from "node:fs";
import { pathToFileURL } from "node:url";

const raiz = new URL("../../", import.meta.url);
const cfg = JSON.parse(readFileSync(process.argv[2], "utf8"));
const logs = [];
for (const m of ["log", "error", "warn"]) console[m] = (...a) => logs.push(a.map(x => typeof x === "string" ? x : JSON.stringify(x)).join(" "));

const db = new PGlite();
await db.exec(`
  create role anon nologin; create role authenticated nologin; create role service_role nologin bypassrls;
  grant usage on schema public to anon, authenticated, service_role;
  create schema emergencia;
  create table public.masterlist (id bigint generated by default as identity (start with 9000) primary key, ceg text, cog text, nome text, nome_do_item text, status text, na_loja boolean default false, id_linha text,
    valor_item numeric, frete_inter numeric, taxa_rf numeric, info_adicionais text, pago_item boolean default false, pago_frete boolean default false, pago_rf boolean default false,
    venc_item date, venc_frete date, venc_rf date);
  create table public.claims (id bigint generated always as identity primary key, joiner_cog text, masterlist_id bigint, ceg text, status text default 'pendente');
  create table public.multas_pagas (id bigint generated always as identity primary key, joiner_cog text, masterlist_id bigint, campo text);
  create table public.joiners (id bigint generated always as identity primary key, cog text unique, nome text, email text, twitter text);
  create table public.push_subscriptions (id bigint generated always as identity primary key, joiner_cog text, endpoint text, p256dh text, auth text);
  grant all on all tables in schema public to service_role;
`);
await db.exec(cfg.setupSql || "");
if (cfg.aplicarS1) await db.exec(readFileSync(new URL("supabase/sync/S1_prune_protegido_aplicar.sql", raiz), "utf8"));
globalThis.__SYNC_DB = db;

const push = [];
globalThis.fetch = async (url, init) => {
  if (String(url).includes("docs.google.com")) return { ok: true, status: 200, text: async () => cfg.csv };
  push.push(String(url)); return { ok: true, status: 200, text: async () => "{}", json: async () => ({}) };
};
process.env.SUPABASE_URL = "http://stub.local"; process.env.SUPABASE_SERVICE_KEY = "stub";

const origem = cfg.scriptSource ?? readFileSync(new URL("scripts/sync-masterlist.js", raiz), "utf8");
if (!origem.includes("from '@supabase/supabase-js'") || !origem.includes("import ws from 'ws';")) throw new Error("o script do sync mudou o formato dos imports: ajuste o executor de teste");
const copia = new URL("scripts/.sync-teste-copia.mjs", raiz);
writeFileSync(copia, origem.replace("from '@supabase/supabase-js'", "from '../tests/helpers/supabase-stub.mjs'").replace("import ws from 'ws';", "const ws = null;"));

let fim = false;
process.on("beforeExit", async () => {
  if (fim) return; fim = true;
  const q = async s => (await db.query(s)).rows;
  const saida = {
    logs, exitCode: process.exitCode ?? 0, push,
    masterlist: await q("select id, ceg, cog, nome, nome_do_item, id_linha, status, pago_item, pago_frete, pago_rf, valor_item from public.masterlist order by id"),
    claims: await q("select id, masterlist_id, status from public.claims order by id"),
    exclusoes: await q("select exists(select 1 from pg_class where relname = 'masterlist_exclusoes') e").then(async r => r[0].e ? await q("select masterlist_id from public.masterlist_exclusoes order by id") : null),
    joiners: await q("select cog, nome, email from public.joiners order by cog"),
  };
  try { unlinkSync(copia); } catch {}
  process.stdout.write("\n@@RESULTADO@@" + JSON.stringify(saida) + "\n");
});
try { await import(copia.href); } catch (e) { logs.push("ERRO AO IMPORTAR: " + e.message); }
