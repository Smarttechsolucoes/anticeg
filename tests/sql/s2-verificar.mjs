// Valida o S2_verificar_leitura.sql (somente leitura) em banco local com dados fictícios. Uso: node tests/sql/s2-verificar.mjs
import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";
const R = new URL("../../supabase/sync/", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
let falhas = 0; const ok = (c, m) => { console.log((c ? "OK   " : "FALHA ") + m); if (!c) falhas++; };
const d = new PGlite();
await d.exec(`
  create table public.masterlist (id bigint generated by default as identity primary key, ceg text, nome text, nome_do_item text, id_linha text);
  create table public.pagamento_demandas (id bigint primary key, status text, itens jsonb);
  insert into public.masterlist (id, ceg, nome, nome_do_item, id_linha) values (1,'A','x','i1','C1'),(2,'A','x','i2','C1'),(3,'A','y','i3',''),(4,'B','z','i4',null),(5,'B','z','i4','C5'),(9,'B','w','i9','C9');
  insert into public.pagamento_demandas values (1,'em_analise','[{"id":1},{"id":777}]'),(2,'pago','[{"id":888},{"id":9}]'),(3,'pago','{"nao":"lista"}'),(4,'pago','[{"id":null}]');
`);
const imp = async () => (await d.query(`select md5((select string_agg(m::text, '|' order by id) from public.masterlist m) || (select string_agg(p::text, '|' order by id) from public.pagamento_demandas p)) h`)).rows[0].h;
const antes = await imp();
const rows = (await d.query(readFileSync(R + "S2_verificar_leitura.sql", "utf8"))).rows;
const v = n => rows.find(r => r.item.startsWith(n))?.valor;
ok(rows.length === 8, "devolve 8 linhas");
ok(await imp() === antes, "não altera nada");
ok(v("linhas na masterlist") === "6" && v("linhas sem id_linha") === "2" && v("valores de id_linha repetidos") === "1" && v("chaves ceg") === "1", "contagens de linhas, sem código, códigos repetidos e chaves repetidas");
ok(v("itens de demandas com id obsoleto") === "2" && v("…em demandas EM ANÁLISE") === "1", "ids obsoletos: 2 no total (777 e 888), 1 em análise; item {id:null} e demanda sem lista não contam");
ok(v("ids emitidos") === "3" && /9/.test(v("último valor")), "ids emitidos e que não existem mais (9 - 6 = 3) e maior id");
console.log(falhas ? `\n${falhas} FALHA(S)` : "\nTODOS OS TESTES PASSARAM"); process.exit(falhas ? 1 : 0);
